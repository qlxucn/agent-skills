#!/usr/bin/env python3
"""Turn a transcribe.py work dir into Markdown. Standard library only.

  render.py draft WORK_DIR   "[hh:mm:ss] A: text" paragraphs for reading   -> WORK_DIR/draft.txt
  render.py terms WORK_DIR   Latin-script words by frequency (misheard tech terms in non-English speech)
  render.py speakers WORK_DIR  per-speaker talk time + sample lines (for confirming speakers with the user)
  render.py final WORK_DIR   WORK_DIR/meta.json + WORK_DIR/summary.md    -> <out_dir>/<date>-<slug>.md

Once WORK_DIR/meta.json exists, draft and speakers apply its reassign/replacements too, so
everything you read or quote matches the final file. Draft and final share the same paragraphs:
every timestamp in draft.txt also starts a paragraph in the final file (summaries can cite them).

meta.json:
  {
    "title": "订单服务迁移评审",
    "slug": "order-service-migration-review",          # lowercase-hyphenated English topic
    "speakers": {"A": "李工（架构师）"},                  # optional; ids may share a name to merge them
    "reassign": {"00:12:41": "C"},                       # optional; move the sentence starting then to C
    "replacements": [["丁丁", "钉钉"], ["Nucos", "Nacos"]], # optional; applied to transcript text in order
    "out_dir": "/path"                                   # optional; default: the audio file's folder
  }
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

SECTION_SEC = 300   # a heading every 5 minutes, for navigation
MAX_PARA = 300      # split a long monologue into paragraphs of roughly this many characters
SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
MARKER = "<!-- generated by the transcript skill; re-rendering overwrites this file -->"
CJK = r"[㐀-鿿]"
ZH_PUNCT = {",": "，", "?": "？", "!": "！", ":": "：", ";": "；"}

LABELS = {
    "zh": dict(date="日期", duration="时长", source="来源", speakers="说话人", method="转写方式",
               method_text="本地自动转写（faster-whisper large-v3-turbo + pyannote community-1），"
                           "可能存在识别或说话人归属错误，关键内容请对照录音核实",
               summary="摘要", transcript="转写全文", speaker="说话人", colon="："),
    "en": dict(date="Date", duration="Duration", source="Source", speakers="Speakers", method="Method",
               method_text="Local automatic transcription (faster-whisper large-v3-turbo + pyannote community-1); "
                           "words or speaker attribution may be wrong, verify key points against the recording",
               summary="Summary", transcript="Transcript", speaker="Speaker", colon=": "),
}


def hms(t):
    t = int(t)
    return f"{t // 3600:02d}:{t % 3600 // 60:02d}:{t % 60:02d}"


def mmss(t):
    return hms(t)[3:] if t < 3600 else hms(t)


def load(work, name):
    path = work / name
    if not path.exists():
        sys.exit(f"Missing {path}")
    return json.loads(path.read_text(encoding="utf-8"))


def zh_punct(text):
    """Whisper emits ASCII punctuation in Chinese; use full-width forms next to CJK characters."""
    return re.sub(rf"(?<={CJK})[,?!:;]|[,?!:;](?={CJK})", lambda m: ZH_PUNCT[m.group()], text)


def paragraphs(segments, zh):
    """Consecutive segments of one speaker form a paragraph, split at 5-minute sections and ~MAX_PARA chars."""
    paras = []
    for s in segments:
        text = zh_punct(s["text"]) if zh else s["text"]
        p = paras[-1] if paras else None
        if (p and p["speaker"] == s["speaker"] and len(p["text"]) < MAX_PARA
                and s["start"] // SECTION_SEC == p["start"] // SECTION_SEC):
            # Whisper segments end at pauses, i.e. clause boundaries: a comma reads right in Chinese.
            sep = (" " if not zh else "" if p["text"][-1] in "，。！？；：、…" else "，")
            p["text"] += sep + text
        else:
            paras.append({"start": s["start"], "speaker": s["speaker"], "text": text})
    if zh:
        for p in paras:
            p["text"] = p["text"].rstrip("，；：、")
            if p["text"][-1] not in "。！？…":
                p["text"] += "。"
    return paras


def is_zh(info):
    return info["language"].startswith("zh")


def load_meta(work):
    return load(work, "meta.json") if (work / "meta.json").exists() else {}


def replaced(text, meta):
    for a, b in meta.get("replacements", []):
        text = text.replace(a, b)
    return text


def reassigned(segments, meta):
    """Diarization mislabels short replies; meta["reassign"] moves single sentences by start time."""
    known = {s["speaker"] for s in segments}
    out = [dict(s) for s in segments]
    for at, spk in meta.get("reassign", {}).items():
        hits = [s for s in out if hms(s["start"]) == at]
        if len(hits) != 1:
            sys.exit(f"reassign {at}: expected one sentence starting at that second, found {len(hits)} (see segments.json)")
        if spk not in known:
            sys.exit(f"reassign {at}: unknown speaker {spk!r}; known: {sorted(known)}")
        hits[0]["speaker"] = spk
    return out


def cmd_draft(work):
    out = work / "draft.txt"
    meta = load_meta(work)
    paras = paragraphs(reassigned(load(work, "segments.json"), meta), is_zh(load(work, "info.json")))
    out.write_text("".join(f"[{hms(p['start'])}] {p['speaker']}: {replaced(p['text'], meta)}\n" for p in paras),
                   encoding="utf-8")
    print(f"{out}  ({len(paras)} lines, {sum(len(p['text']) for p in paras)} chars)")


def cmd_terms(work):
    counts = Counter(w for s in load(work, "segments.json")
                     for w in re.findall(r"[A-Za-z][A-Za-z0-9._-]*", s["text"]))
    print("  ".join(f"{w}×{n}" for w, n in counts.most_common(200)))


def cmd_speakers(work):
    meta, zh = load_meta(work), is_zh(load(work, "info.json"))
    stats = {}
    for s in reassigned(load(work, "segments.json"), meta):
        stats.setdefault(s["speaker"], []).append(s)
    for spk, segs in stats.items():
        talk = sum(s["end"] - s["start"] for s in segs)
        name = meta.get("speakers", {}).get(spk, "(no name yet)")
        print(f"{spk} → {name}: talk time {hms(talk)}, {len(segs)} segments, first at {hms(segs[0]['start'])}")
        longest = sorted(segs, key=lambda s: len(s["text"]), reverse=True)[:4]
        for s in sorted(longest, key=lambda s: s["start"]):
            print(f"  - [{hms(s['start'])}] {replaced(zh_punct(s['text']) if zh else s['text'], meta)}")


def cmd_final(work):
    info, segments, meta = load(work, "info.json"), load(work, "segments.json"), load(work, "meta.json")
    summary_path = work / "summary.md"
    if not summary_path.exists():
        sys.exit(f"Missing {summary_path}")
    for key in ("title", "slug"):
        if not meta.get(key):
            sys.exit(f"meta.json needs '{key}'")
    if not SLUG.match(meta["slug"]):
        sys.exit(f"slug must be lowercase-hyphenated ascii, got {meta['slug']!r}")

    zh = is_zh(info)
    L = LABELS["zh" if zh else "en"]
    names = {spk: meta.get("speakers", {}).get(spk, f"{L['speaker']} {spk}")
             for spk in dict.fromkeys(s["speaker"] for s in segments)}
    unknown = set(meta.get("speakers", {})) - set(names)
    if unknown:
        sys.exit(f"meta.json names speakers that do not exist: {sorted(unknown)}; known: {sorted(names)}")

    out_dir = Path(meta.get("out_dir") or Path(info["source"]).parent).expanduser()
    out = out_dir / f"{info['date']}-{meta['slug']}.md"
    if out.exists() and out.read_text(encoding="utf-8").partition("\n")[0] != MARKER:
        sys.exit(f"{out} exists and was not generated by this skill; choose another slug or out_dir")

    lines = [
        MARKER, f"# {meta['title']}", "",
        f"- **{L['date']}**{L['colon']}{info['date']}",
        f"- **{L['duration']}**{L['colon']}{hms(info['duration_seconds'])}",
        f"- **{L['source']}**{L['colon']}`{Path(info['source']).name}`",
        f"- **{L['speakers']}**{L['colon']}" + " · ".join(dict.fromkeys(names.values())),
        f"- **{L['method']}**{L['colon']}{L['method_text']}",
        "", f"## {L['summary']}", "", summary_path.read_text(encoding="utf-8").strip(), "",
        f"## {L['transcript']}", "",
    ]
    section = -1 if info["duration_seconds"] > SECTION_SEC else 0  # no headings for short clips
    for p in paragraphs(reassigned(segments, meta), zh):
        if p["start"] // SECTION_SEC != section:
            section = int(p["start"] // SECTION_SEC)
            lines += [f"### {mmss(section * SECTION_SEC)} – {mmss((section + 1) * SECTION_SEC)}", ""]
        lines += [f"**{names[p['speaker']]}** [{hms(p['start'])}]{L['colon']}{replaced(p['text'], meta)}", ""]

    out.write_text("\n".join(lines), encoding="utf-8")
    print(out)


def main():
    commands = {"draft": cmd_draft, "terms": cmd_terms, "speakers": cmd_speakers, "final": cmd_final}
    if len(sys.argv) != 3 or sys.argv[1] not in commands:
        sys.exit(__doc__)
    commands[sys.argv[1]](Path(sys.argv[2]).expanduser())


if __name__ == "__main__":
    main()
